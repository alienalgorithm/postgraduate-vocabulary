"""Build A/story/storyboard.json from content.json + music/map.json.
Every beat-locked time is computed from the bar grid of score.wav (94 BPM, bar k at map.bars[k])."""
import json, copy, math, os, sys

A = sys.argv[1]
content = json.load(open(os.path.join(A, 'story/content.json')))
mp = json.load(open(os.path.join(A, 'music/map.json')))
BARS = mp['bars']
BEAT = mp['beat']

def T(k, q=0.0):
    """global time of bar k, plus q beats"""
    return BARS[k] + q * BEAT

# ---------- scene plan (bar numbers are the map's 0-based bar indices) ----------
PLAN = [('s01', 0), ('s02', 4), ('s03', 12), ('s04', 19), ('s05', 28), ('s06', 35), ('s07', 44),
        ('s08', 48), ('s09', 57), ('s10', 63), ('s11', 70)]
TOTAL = mp['total']
START = {}
for i, (sid, k) in enumerate(PLAN):
    START[sid] = 0.0 if k == 0 else round(BARS[k], 4)
END = {}
for i, (sid, k) in enumerate(PLAN):
    END[sid] = START[PLAN[i + 1][0]] if i + 1 < len(PLAN) else TOTAL

def R(sid, k, q=0.0):
    return round(T(k, q) - START[sid], 3)

def tx(i, o, text, role, **kw):
    d = {'in': round(i, 3), 'out': round(o, 3), 'text': text, 'role': role}
    d.update(kw)
    return d

C = {s['id']: s for s in content['scenes']}

def section_of(t):
    for s in mp['sections']:
        if s['start'] - 1e-6 <= t < s['end'] - 1e-6:
            return s['name']
    return mp['sections'][-1]['name']

def barbeat(g):
    k = max(i for i, b in enumerate(BARS) if b <= g + 0.02)
    q = (g - BARS[k]) / BEAT
    return k, q

