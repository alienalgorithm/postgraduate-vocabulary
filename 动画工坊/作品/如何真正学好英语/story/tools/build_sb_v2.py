EVENTS = {e['t']: e for e in en['events']}

def near_idx(lst, t):
    return min(range(len(lst)), key=lambda i: abs(lst[i] - t))

DOWN = {b['n']: near_idx(BEATS, b['t']) for b in BINFO}   # bar number (1-based) -> index of its downbeat in BEATS

def G(n, q=0.0):
    """global time of bar n (1-based, as in map.bar_info) plus q beats (fractions = 8ths/16ths)"""
    i = DOWN[n] + int(q)
    f = q - int(q)
    return round(BEATS[i] + f * BEAT, 4)

def barbeat(g):
    n = max(b['n'] for b in BINFO if b['t'] <= g + 1e-6)
    i = max(k for k, b in enumerate(BEATS) if b <= g + 1e-6)
    q = i - DOWN[n] + (g - BEATS[i]) / BEAT
    return n, round(1 + q, 3)

def hitnote(g):
    for t, s in HITS.items():
        if abs(t - g) < 0.01:
            ev = EVENTS.get(t)
            return '，%s %.2f' % ((ev['name'] if ev else 'hit'), s)
    for t, ev in EVENTS.items():
        if abs(t - g) < 0.01:
            return '，%s' % ev['name']
    return ''

def fmt_beat(b):
    s = ('%.3f' % b).rstrip('0').rstrip('.')
    return s

def tx(i, o, text, role, **kw):
    d = {'in': round(i, 4), 'out': round(o, 4), 'text': text, 'role': role}
    d.update(kw)
    return d

def scene_energy(start, dur):
    a, b = int(start * en['fps']), int((start + dur) * en['fps'])
    seg = en['values'][a:b]
    return round(sum(seg) / len(seg), 3), round(max(seg), 3)

